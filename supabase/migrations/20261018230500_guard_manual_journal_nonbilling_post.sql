-- Guard manual journals from acting as sale/expense/VAT billing.
-- Source-generated invoices, approved reversals and historical posted records are untouched.
-- IMPORTANT: Never globally set allow_manual_entries=false for mapped accounts:
-- the canonical invoice/expense posting RPC checks that flag as well.
BEGIN;

CREATE OR REPLACE FUNCTION public.guard_manual_journal_nonbilling_post()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = public, pg_temp AS $guard$
BEGIN
  IF NEW.status IS DISTINCT FROM 'posted'
     OR OLD.status IS DISTINCT FROM 'draft' THEN
    RETURN NEW;
  END IF;

  -- Opposite journal generated by an authorized reversal; not new billing.
  IF NEW.reversal_of_entry_id IS NOT NULL THEN RETURN NEW; END IF;

  -- Source-document generated journals carry all three traceability values.
  -- Preserve the canonical Invoice/Expense -> Journal posting path.
  IF NEW.source_document_id IS NOT NULL
     AND NULLIF(btrim(coalesce(NEW.source_document_type,'')), '') IS NOT NULL
     AND NULLIF(btrim(coalesce(NEW.source_module,'')), '') IS NOT NULL
  THEN RETURN NEW; END IF;

  IF EXISTS (
    SELECT 1
      FROM public.journal_lines l
      JOIN public.chart_of_accounts a ON a.id=l.account_id AND a.company_id=NEW.company_id
     WHERE l.entry_id=NEW.id AND l.company_id=NEW.company_id
       AND (
         lower(a.type) IN ('revenue','income','expense')
         OR a.code IN ('1150','2120')
         OR a.name ~* '(input|output)[[:space:]]+vat'
         OR EXISTS (
           SELECT 1 FROM public.account_mappings m
            WHERE m.company_id=NEW.company_id AND m.account_id=a.id
              AND m.mapping_key IN ('input_vat','output_vat')
         )
       )
  ) THEN
    RAISE EXCEPTION USING ERRCODE='23514',
      MESSAGE='Manual journals cannot post Income, Expense or VAT control accounts. Use the Sale/Expense Invoice workflow; authorized adjustments need a separate controlled process.';
  END IF;
  RETURN NEW;
END;
$guard$;

DROP TRIGGER IF EXISTS zzz_manual_journal_nonbilling_post ON public.journal_entries;
CREATE TRIGGER zzz_manual_journal_nonbilling_post
BEFORE UPDATE OF status ON public.journal_entries
FOR EACH ROW
WHEN (OLD.status='draft' AND NEW.status='posted')
EXECUTE FUNCTION public.guard_manual_journal_nonbilling_post();

COMMIT;
